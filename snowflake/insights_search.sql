-- Run only AFTER uploading INSIGHT_CHUNKS with scripts.prepare_insights --load.
-- Search serving/indexing incurs charges independently of the warehouse monitor.
USE DATABASE SIGNAL_STARTS_DEMO;
USE SCHEMA PUBLIC;
CREATE CORTEX SEARCH SERVICE IF NOT EXISTS INSIGHTS_SEARCH
 ON CONTENT
 ATTRIBUTES PRODUCT_ID,TERRITORY_ID,PERIOD_KEY,PUBLISHED_DAY
 WAREHOUSE=SIGNAL_DEMO_WH
 TARGET_LAG='1 day'
 AS SELECT CHUNK_ID,DOCUMENT_ID,TITLE,CONTENT,PERIOD_MONTH,PERIOD_KEY,PUBLISHED_DAY,
 TERRITORY_ID,PRODUCT_ID,TOPIC,AUTHOR_ROLE,EVIDENCE_STATUS,VERSION FROM INSIGHT_CHUNKS;
GRANT USAGE ON CORTEX SEARCH SERVICE INSIGHTS_SEARCH TO ROLE SIGNAL_DEMO_AGENT_ROLE;

